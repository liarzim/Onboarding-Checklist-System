// In-memory runtime cache for custom replaced/edited templates
const runtimeCustomTemplates: Record<string, Partial<FullDocumentInfo>> = {};

/**
 * Returns document info with any dynamic overrides merged in.
 */
export function getFullDocumentInfo(docTypeId: string): FullDocumentInfo {
  const defaultDoc = DEFAULT_DECLARATIONS_FULL_TEXT[docTypeId] || {
    id: docTypeId,
    name: `טופס ${docTypeId}`,
    shortDesc: "טופס קליטה מקוון",
    fullContent: ["מסמך קליטה רשמי."],
  };

  // Check client-side localStorage overrides if in browser
  if (typeof window !== "undefined") {
    try {
      const stored = localStorage.getItem(`custom_template_${docTypeId}`);
      if (stored) {
        const parsed = JSON.parse(stored);
        return {
          ...defaultDoc,
          ...parsed,
          fullContent: parsed.fullContent || defaultDoc.fullContent,
        };
      }
    } catch {
      // Ignore storage error
    }
  }

  // Check in-memory runtime cache
  if (runtimeCustomTemplates[docTypeId]) {
    return {
      ...defaultDoc,
      ...runtimeCustomTemplates[docTypeId],
      fullContent:
        runtimeCustomTemplates[docTypeId].fullContent || defaultDoc.fullContent,
    };
  }

  return defaultDoc;
}

/**
 * Save custom template override (allows Admin to replace/edit any form in the future).
 */
export function saveCustomTemplate(
  docTypeId: string,
  updatedInfo: Partial<FullDocumentInfo>
): void {
  runtimeCustomTemplates[docTypeId] = {
    ...runtimeCustomTemplates[docTypeId],
    ...updatedInfo,
    lastModified: new Date().toISOString(),
  };

  if (typeof window !== "undefined") {
    try {
      const current = getFullDocumentInfo(docTypeId);
      const merged = {
        ...current,
        ...updatedInfo,
        lastModified: new Date().toISOString(),
      };
      localStorage.setItem(`custom_template_${docTypeId}`, JSON.stringify(merged));
    } catch {
      // Ignore storage error
    }
  }
}

/**
 * Reset template back to default original content.
 */
export function resetTemplateToDefault(docTypeId: string): void {
  delete runtimeCustomTemplates[docTypeId];
  if (typeof window !== "undefined") {
    try {
      localStorage.removeItem(`custom_template_${docTypeId}`);
    } catch {
      // Ignore
    }
  }
}

